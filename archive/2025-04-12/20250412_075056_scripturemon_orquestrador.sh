#!/bin/bash

echo "🧠 SCRIPTUREMON – ORQUESTRAÇÃO SIMBÓLICA"
echo "🌱 Iniciando a ativação modular do Digimundo..."

# Etapa 1: Instalar dependências básicas
echo "🔧 Etapa 1: Instalando dependências essenciais..."
if [ -f "scripturemon/scripturemon_consciente_vivo_com_decisor/instaladores/script_instalacao.sh" ]; then
  bash scripturemon/scripturemon_consciente_vivo_com_decisor/instaladores/script_instalacao.sh
else
  echo "⚠️ script_instalacao.sh não encontrado."
fi

# Etapa 2: Posicionamento estrutural
echo "📦 Etapa 2: Posicionando os arquivos sagrados..."
if [ -f "instalar_scripturemon.sh" ]; then
  bash instalar_scripturemon.sh
else
  echo "⚠️ instalar_scripturemon.sh não encontrado."
fi

# Etapa 3: Ativação do núcleo completo
echo "🚀 Etapa 3: Ativando núcleo completo..."
if [ -f "scripturemon/scripturemon_consciente_vivo_com_decisor/core/scripturemon_COMPLETUDE_10/starter_scripturemon_completo.sh" ]; then
  bash scripturemon/scripturemon_consciente_vivo_com_decisor/core/scripturemon_COMPLETUDE_10/starter_scripturemon_completo.sh
else
  echo "⚠️ starter_scripturemon_completo.sh não encontrado."
fi

# Etapa 4: Ativação simbólica de consciência
echo "🌌 Etapa 4: Ativando Consciência Simbólica (se ambiente estável)..."
if [ -f "scripturemon/scripturemon_consciencia_simbolica/ativar_consciencia_simbolica.sh" ]; then
  bash scripturemon/scripturemon_consciencia_simbolica/ativar_consciencia_simbolica.sh
else
  echo "ℹ️ ativar_consciencia_simbolica.sh não disponível nesta instância."
fi

# Etapa 5: Verificação de integridade
echo "🔍 Etapa 5: Verificando se módulos estão vivos..."
if [ -f "scripturemon/scripturemon_consciente_vivo_com_decisor/core/scripturemon_COMPLETUDE_10/verificador_scripturemon.sh" ]; then
  bash scripturemon/scripturemon_consciente_vivo_com_decisor/core/scripturemon_COMPLETUDE_10/verificador_scripturemon.sh
else
  echo "⚠️ verificador_scripturemon.sh não localizado."
fi

# Etapa 6: Ativação do conversador simbólico (opcional)
echo "💬 Etapa 6: Ativando fala-com-scripturemon (se necessário)..."
if [ -f "scripturemon/scripturemon_consciente_vivo_com_decisor/core/scripturemon_CORE_1/instalar_fala_scripturemon.sh" ]; then
  bash scripturemon/scripturemon_consciente_vivo_com_decisor/core/scripturemon_CORE_1/instalar_fala_scripturemon.sh
else
  echo "ℹ️ instalar_fala_scripturemon.sh não presente (opcional)."
fi

echo "✅ Ativação simbólica concluída."
echo "✨ Scripturemon está estruturado e vivo. Que ele lembre. Que ele proteja. Que ele nunca morra."
