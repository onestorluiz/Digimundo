    def create_missing_symbols(self, missing_concepts):
        """Create symbols for missing concepts"""
        print("\n🔧 CRIANDO SÍMBOLOS PARA CONCEITOS FALTANTES...")
        
        # Get unused Unicode characters
        used_symbols = set(self.current_digilang.values())
        
        # Large Unicode ranges for new symbols
        available_symbols = []
        
        # Egyptian Hieroglyphs (1071 chars)
        for i in range(0x13000, 0x1342E):
            char = chr(i)
            if char not in used_symbols:
                available_symbols.append(char)
                
        # Cuneiform (922 chars)
        for i in range(0x12000, 0x123FF):
            char = chr(i)
            if char not in used_symbols:
                available_symbols.append(char)
                
        # Linear B Ideograms (123 chars)
        for i in range(0x10080, 0x100FF):
            char = chr(i)
            if char not in used_symbols:
                available_symbols.append(char)
                
        # Vai Syllabary (300 chars)
        for i in range(0xA500, 0xA63F):
            char = chr(i)
            if char not in used_symbols:
                available_symbols.append(char)
                
        print(f"   Símbolos únicos disponíveis: {len(available_symbols):,}")
        
        # Create new entries
        new_symbols = {}
        symbol_idx = 0
        
        for pt_concept, en_concept in missing_concepts[:len(available_symbols)]:
            if symbol_idx < len(available_symbols):
                new_symbols[en_concept] = available_symbols[symbol_idx]
                symbol_idx += 1
                
        print(f"   Novos símbolos criados: {len(new_symbols)}")
        
        return new_symbols
        
    def update_digilang(self, new_symbols):
        """Update DigiLang dictionary with new symbols"""
        print("\n📝 ATUALIZANDO DIGILANG...")
        
        # Load current dictionary
        with open(self.digilang_path, 'r', encoding='utf-8') as f:
            digilang = json.load(f)
            
        # Add new symbols
        digilang['symbols'].update(new_symbols)
        
        # Add to digimundo category
        if 'digimundo' not in digilang['categories']:
            digilang['categories']['digimundo'] = {}
            
        digilang['categories']['digimundo'].update(new_symbols)
        
        # Update metadata
        digilang['metadata']['total_symbols'] = len(digilang['symbols'])
        digilang['metadata']['last_update'] = datetime.now().isoformat()
        digilang['metadata']['digimundo_analysis'] = True
        
        # Save updated dictionary
        output_path = self.base_path / "core/digilang/DIGILANG_DIGIMUNDO_COMPLETE.json"
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(digilang, f, indent=2, ensure_ascii=False)
            
        print(f"   ✅ Salvo em: {output_path}")
        print(f"   Total de palavras: {len(digilang['symbols']):,}")
        
        return output_path
        
