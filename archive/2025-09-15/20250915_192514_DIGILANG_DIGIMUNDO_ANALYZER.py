    def analyze_file(self, file_path):
        """Analyze individual file"""
        try:
            with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                content = f.read()
                
            self.file_count += 1
            
            # Extract all words (including Portuguese)
            words = re.findall(r'\b[a-zA-Z_][a-zA-Z0-9_]{2,}\b', content)
            
            for word in words:
                word_lower = word.lower()
                self.all_words[word_lower] += 1
                
                # Extract concepts (remove common prefixes/suffixes)
                concept = self.extract_concept(word_lower)
                if concept:
                    self.concepts.add(concept)
                    
            # Count lines
            self.line_count += content.count('\n')
            
            # Extract specific Digimundo concepts
            self.extract_digimundo_specific(content)
            
            if self.file_count % 10 == 0:
                print(f"   {self.file_count} arquivos analisados...")
                
        except Exception as e:
            pass  # Skip files that can't be read
            
    def extract_concept(self, word):
        """Extract base concept from word"""
        # Remove common programming suffixes
        suffixes = ['ing', 'ed', 'er', 's', 'es', 'tion', 'ment', 'ity', 'ness', 'able', 'ible']
        
        for suffix in suffixes:
            if word.endswith(suffix) and len(word) > len(suffix) + 2:
                word = word[:-len(suffix)]
                break
                
        # Remove common prefixes
        prefixes = ['un', 'pre', 'post', 'anti', 'de', 're', 'dis', 'over', 'under', 'out']
        
        for prefix in prefixes:
            if word.startswith(prefix) and len(word) > len(prefix) + 2:
                word = word[len(prefix):]
                break
                
        return word if len(word) > 2 else None
        
