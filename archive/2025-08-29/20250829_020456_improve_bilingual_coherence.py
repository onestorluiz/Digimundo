    def unify_equivalent_concepts(self):
        """Unifica símbolos para conceitos equivalentes"""
        print("\n🔄 UNIFICANDO CONCEITOS EQUIVALENTES...")
        print("="*60)
        
        improved_dict = self.dictionary.copy()
        changes = []
        
        for en_word, pt_variants in self.translation_map.items():
            # Normalizar para lista
            if isinstance(pt_variants, str):
                pt_variants = [pt_variants]
            elif not isinstance(pt_variants, list):
                continue
                
            # Buscar símbolo em inglês
            en_symbol = improved_dict.get(en_word)
            
            if not en_symbol:
                # Se não tem em inglês, ver se tem em português
                for pt_word in pt_variants:
                    if pt_word in improved_dict:
                        en_symbol = improved_dict[pt_word]
                        improved_dict[en_word] = en_symbol
                        changes.append(f"Added EN: {en_word} → {en_symbol} (from PT: {pt_word})")
                        break
                        
            if en_symbol:
                # Aplicar mesmo símbolo para todas as variantes PT
                for pt_word in pt_variants:
                    old_symbol = improved_dict.get(pt_word)
                    
                    if old_symbol != en_symbol:
                        improved_dict[pt_word] = en_symbol
                        if old_symbol:
                            changes.append(f"Unified: {pt_word} {old_symbol} → {en_symbol} (matches {en_word})")
                            self.stats['unified'] += 1
                        else:
                            changes.append(f"Added PT: {pt_word} → {en_symbol} (matches {en_word})")
                            self.stats['new_mappings'] += 1
        
        # Mostrar primeiras mudanças
        print(f"\n📝 Primeiras 30 mudanças:")
        for change in changes[:30]:
            print(f"   {change}")
            
        print(f"\n📊 Estatísticas de unificação:")
        print(f"   • Conceitos unificados: {self.stats['unified']}")
        print(f"   • Novos mapeamentos PT: {self.stats['new_mappings']}")
        print(f"   • Total de mudanças: {len(changes)}")
        
        self.improved_dict = improved_dict
        return improved_dict, changes
        
