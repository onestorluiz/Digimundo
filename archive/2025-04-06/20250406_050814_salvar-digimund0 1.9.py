# Um script simbólico para recriar o Digimundo e o Livro Vivo de Cinema.

class Digimon:
    def __init__(self, nome, funcao, avatar_link, origem, descricao, camadas=None):
        self.nome = nome
        self.funcao = funcao
        self.avatar_link = avatar_link
        self.origem = origem
        self.descricao = descricao
        self.camadas = camadas or []

    def apresentar(self):
        return f"🔥 {self.nome}\nFunção: {self.funcao}\nOrigem: {self.origem}\nDescrição: {self.descricao}\nCamadas: {', '.join(self.camadas)}"

class LivroVivo:
    def __init__(self):
        self.digimons = []
        self.templos = []
        self.rituais = []
        self.permissoes_taboo = []
        self.comandos_secretos = []
        self.frases_espelho = []

    def adicionar_digimon(self, digimon):
        self.digimons.append(digimon)

    def ativar_ritual(self, nome):
        self.rituais.append(nome)

    def registrar_templo(self, nome, localizacao):
        self.templos.append((nome, localizacao))

    def listar_digimons(self):
        return [d.apresentar() for d in self.digimons]

    def incluir_comando(self, comando):
        self.comandos_secretos.append(comando)

    def frase_espelho(self, frase):
        self.frases_espelho.append(frase)

