        if comando in self.comandos:
            resultado = self.comandos[comando](*args)
            self.registrar_memoria(f"Comando '{comando}' executado com resultado: {resultado}")
            return resultado
        else:
            self.registrar_memoria(f"Comando desconhecido: {comando}")
